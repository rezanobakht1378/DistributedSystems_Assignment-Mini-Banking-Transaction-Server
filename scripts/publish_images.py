"""Build the application image, push it to Docker Hub and point the
deployment at it.

    docker login
    python scripts/publish_images.py --user <dockerhub-user>             # tag from k8s/base
    python scripts/publish_images.py --user <dockerhub-user> --tag 1.3.1
    kubectl apply -k k8s/overlays/dockerhub                              # single node
    kubectl apply -k k8s/overlays/multi-vm-dockerhub                     # three VMs

One image serves the gateway, the shard apps, the database controller and
the database bootstrap init containers. PostgreSQL and Prometheus use the
official images (postgres:16, prom/prometheus:v2.55.1).
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCAL = "mini-banking-app"


def run(*command: str) -> None:
    print("+", " ".join(command), flush=True)
    subprocess.run(command, check=True)


def base_tag() -> str:
    text = (ROOT / "k8s" / "base" / "kustomization.yaml").read_text(encoding="utf-8")
    return re.search(r'newTag:\s*"([^"]+)"', text).group(1)


def write_overlay(name: str, base: str, repository: str, tag: str) -> Path:
    overlay = ROOT / "k8s" / "overlays" / name
    overlay.mkdir(parents=True, exist_ok=True)
    (overlay / "kustomization.yaml").write_text(
        "# Generated by scripts/publish_images.py: the same stack, pulling the\n"
        "# application image from Docker Hub instead of a side-loaded copy.\n"
        "apiVersion: kustomize.config.k8s.io/v1beta1\n"
        "kind: Kustomization\n"
        "resources:\n"
        f"  - {base}\n"
        "images:\n"
        f"  - name: {LOCAL}\n"
        f"    newName: {repository}\n"
        f"    newTag: \"{tag}\"\n",
        encoding="utf-8")
    return overlay


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0],
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--user", default=os.getenv("DOCKERHUB_USER"),
                        help="Docker Hub account (or set DOCKERHUB_USER)")
    parser.add_argument("--tag", default=None, help="default: newTag in k8s/base/kustomization.yaml")
    parser.add_argument("--no-build", action="store_true", help="push the existing local image")
    parser.add_argument("--no-push", action="store_true", help="only build, tag and write overlays")
    args = parser.parse_args()
    if not args.user:
        parser.error("--user (or DOCKERHUB_USER) is required")
    tag = args.tag or base_tag()
    repository = f"docker.io/{args.user}/{LOCAL}"
    if not args.no_build:
        run("docker", "build", "-t", f"{LOCAL}:{tag}", str(ROOT))
    for reference in (f"{repository}:{tag}", f"{repository}:latest"):
        run("docker", "tag", f"{LOCAL}:{tag}", reference)
        if not args.no_push:
            run("docker", "push", reference)
    single = write_overlay("dockerhub", "../../base", repository, tag)
    multi = write_overlay("multi-vm-dockerhub", "../multi-vm", repository, tag)
    print(f"image: {repository}:{tag}")
    print(f"overlays: {single.relative_to(ROOT)}, {multi.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
